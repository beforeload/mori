//! UI language: Simplified Chinese, English, and Traditional Chinese.
//! Simplified strings in the source are the keys. Missing entries stay in Simplified Chinese.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::LazyLock;

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Language {
    #[default]
    ZhHans,
    En,
    ZhHant,
}

impl Language {
    pub const ALL: [Language; 3] = [Language::ZhHans, Language::En, Language::ZhHant];

    /// The name of the language, written in that language.
    pub fn native_name(self) -> &'static str {
        match self {
            Language::ZhHans => "简体中文",
            Language::En => "English",
            Language::ZhHant => "繁體中文",
        }
    }

    pub fn gpui_code(self) -> &'static str {
        match self {
            Language::ZhHans => "zh-CN",
            Language::En => "en",
            Language::ZhHant => "zh-TW",
        }
    }

    pub fn reply_instruction(self) -> &'static str {
        match self {
            Language::ZhHans => "请使用简体中文回答。",
            Language::En => "Reply in English.",
            Language::ZhHant => "請使用繁體中文回答。",
        }
    }
}

static LANG: AtomicU8 = AtomicU8::new(0);

pub fn language() -> Language {
    match LANG.load(Ordering::Relaxed) {
        1 => Language::En,
        2 => Language::ZhHant,
        _ => Language::ZhHans,
    }
}

pub fn set_language(lang: Language) {
    LANG.store(
        match lang {
            Language::ZhHans => 0,
            Language::En => 1,
            Language::ZhHant => 2,
        },
        Ordering::Relaxed,
    );
}

/// macOS preferred language. Tests stay on Simplified Chinese.
pub fn system_language() -> Language {
    if cfg!(test) {
        return Language::ZhHans;
    }
    let text = std::process::Command::new("defaults")
        .args(["read", "-g", "AppleLanguages"])
        .output()
        .ok()
        .and_then(|out| String::from_utf8(out.stdout).ok())
        .unwrap_or_default();
    let first = text.split('"').nth(1).unwrap_or("").to_ascii_lowercase();
    if first.contains("hant") || first.contains("zh-tw") || first.contains("zh_tw") || first.contains("zh-hk") || first.contains("zh_hk") {
        Language::ZhHant
    } else if first.starts_with("en") {
        Language::En
    } else {
        Language::ZhHans
    }
}

pub fn tr<'a>(zh: &'a str) -> &'a str {
    match language() {
        Language::ZhHans => zh,
        Language::En => EN.get(zh).copied().unwrap_or(zh),
        Language::ZhHant => HANT.get(zh).copied().unwrap_or(zh),
    }
}

/// Fills `{}` placeholders in order. The translated template keeps the same count.
pub fn tf(zh: &str, args: &[&dyn std::fmt::Display]) -> String {
    let template = tr(zh).to_string();
    let mut out = String::new();
    let mut rest = template.as_str();
    for arg in args {
        match rest.split_once("{}") {
            Some((head, tail)) => {
                out.push_str(head);
                out.push_str(&arg.to_string());
                rest = tail;
            }
            None => break,
        }
    }
    out.push_str(rest);
    out
}

#[macro_export]
macro_rules! t {
    ($zh:literal) => {
        $crate::i18n::tr($zh)
    };
    ($zh:literal, $($arg:expr),+ $(,)?) => {
        $crate::i18n::tf($zh, &[$(&$arg as &dyn std::fmt::Display),+])
    };
}

